"""
Tests the ADDITIVE get_cell_emb reconstruction against the already-refuted alternatives
AND the reindex-to-dataset pooling mode (ROADMAP.md §16), on a single shared forward pass
per batch (cheap: merged_decodings is already produced either way, exp_to_out and the
reindex-to-dataset gather both add negligible compute):

  (A) sum_pool  = merged_decodings.sum(-1)                    current pipeline default
  (B) exp_only  = model.exp_to_out(merged_decodings).squeeze(-1)  refuted: ~0.70, matches
                                                                    the paper's own "Raw"
                                                                    baseline (see ROADMAP.md §14.2)
  (C) additive  = sum_pool + exp_only, still in MODEL gene-vocabulary space           tested,
                                                                    refuted at n=20 (see §14.2)
  (D) eq11_reindexed = additive, reindexed onto the DATASET's own gene ordering        NEW
                        (filler='mean') BEFORE summing -- the actual paper Equation (11)
                        recipe, ported from a colleague's independently run notebook that
                        scored ASW=0.9212 on this exact checkpoint (see ROADMAP.md §16).
                        Output dimensionality is the dataset's own gene count, not
                        max_seq_len -- unlike A/B/C, D ignores --pooling's full/measured-
                        only choice entirely (it's a third, mutually exclusive axis).

Ported into the repo from an ephemeral scratchpad harness a Round-2/3 research agent
built during the wf_d1c898a4-2d1 workflow (see ROADMAP.md §14.2) — fixed to be
CLI-parameterized and batched (the original was single-batch, n=20 only, would OOM at
n=500+), and to inherit --bio-conservation from eval_utils.py automatically (no code
change needed there — this script's evaluate() call now gets NMI/ARI/isolated-F1 for
free, closing the exact gap Round 3 flagged as a required fix before running).

CITATION STATUS, UPDATED — this IS the paper's literal Equation (11). A prior note here
claimed the supporting quote "very likely doesn't exist" based on a failed grep for one
specific paraphrase ("concatenating contextualized representations with reconstructed
expressions, followed by sum-pooling"). A follow-up direct byte-level re-read of
research/papers/scLong_NatCommun2026_main_extracted.txt (opened as
open(path,'rb').read().decode('utf-8', errors='replace') — the file has 3 literal NUL
bytes, first at offset 2415, that make plain grep return false negatives) found the
actual equation at offset ~100504, differently worded than the paraphrase that was
searched for before:
    "Let E ∈ R^(N×D) denote the contextualized representations produced by the full-
    length Performer encoder ... where D = 200 ... Let x' ∈ R^N denote the reconstructed
    gene expression vector generated by the model's ... decoder ... We concatenate E and
    x' to form a matrix V ∈ R^(N×(D+1)). We then apply sum pooling across the rows of V
    ...: v_i = sum_{j=1}^{D+1} V_ij.  (11)"
Cross-checked against ding_models.py DualEncoderSCFM.forward() (lines 349-431): the
paper's "full-length Performer encoder" is the code's self.decoder (a Performer taking
the merged dual-encoder output x_enc_merge and self-attending over all 27,875 positions);
its output, after self.decode_norm, is recorded as output["merged_decodings"] -- i.e.
E == merged_decodings. exp_to_out is applied to that SAME post-decode_norm tensor,
producing x'. So Eq. (11) is *exactly* rowsum(merged_decodings) + exp_to_out(
merged_decodings).squeeze(-1) -- i.e. exactly the A+B additive formula already
implemented below, confirmed via a tiny float32 CPU check (concat-then-rowsum vs.
sum-then-add, N=37/D=200 synthetic, seed=42: max abs diff 1.9e-6). The paper's own
"full-length Performer encoder" terminology for this stage is a naming choice, not a
different tensor -- the checkpoint's own hyperparameter pickle (gene_meta/
gocont_4096_48m_pretrain_1b_mix.pkl, safely read via `python3 -m pickletools`, no
unpickling) confirms dec_depth=2/dec_heads=8/dec_dim_head=64/base_dim=200, matching the
paper's "This final encoder has 2 layers, 8 attention heads, and a hidden dimension of
200" verbatim. Do not re-litigate whether this formula has textual support -- it does;
what remains genuinely open is only whether it wins empirically at adequate n (see below).

--normalization (NEW): the CLOSED n=20 result (job 316699: A=0.8283, C=0.7834, see
ROADMAP.md §14.2) never applied any renormalization -- it read adata.X as-is, i.e. it
implicitly ran under --normalization as-shipped, NOT the `cpm` recipe that produced this
project's actual best/reference config (0.8550, job 316352). That makes the existing
"CLOSED, NEGATIVE" verdict an as-shipped/n=20 result, not a same-config comparison against
the number this project treats as its ceiling. This flag closes that gap by porting the
exact renormalization functions from run_zero_shot_batch_integration.py (imported below,
not reimplemented, to avoid drift) so this script can be run under the identical
map-v2_hgnc_plus_biomart_synonyms_pool-measured-only_norm-cpm config as the 0.8550 run,
changing ONLY get_cell_emb.

Run (inside the container) — TWO recommended full-scale configs (A/B/C/D all computed
together in one pass each, so each of these costs the same as any other single full-scale
job):

  1. Faithful replication of the colleague's 0.9212 notebook run (--normalization
     shipped-max10, their exact preprocessing) -- confirms D is a correct, working port
     before combining it with anything this project added independently:
    apptainer exec --nv --cleanenv --env PYTHONNOUSERSITE=1 \
        --bind /groups/tprice/pipelines:/groups/tprice/pipelines \
        --bind /scratch/juno/$USER:/scratch/juno/$USER \
        --bind $(pwd)/pipeline:/pipeline --bind $(pwd)/experiments:/experiments \
        container/sclong_v1.0.0.sif \
        python /experiments/additive_pooling_test.py \
          --data-root /groups/tprice/pipelines/references/sclong \
          --output-dir /scratch/juno/$USER/sclong_results/additive_pooling_replication \
          --n-cells all --seed 42 \
          --gene-mapping-version v2_hgnc_plus_biomart_synonyms --pooling full \
          --normalization shipped-max10

  2. This project's own best normalization (cpm) stacked with the new pooling mode --
     tests whether the two independent gains compound:
    apptainer exec --nv --cleanenv --env PYTHONNOUSERSITE=1 \
        --bind /groups/tprice/pipelines:/groups/tprice/pipelines \
        --bind /scratch/juno/$USER:/scratch/juno/$USER \
        --bind $(pwd)/pipeline:/pipeline --bind $(pwd)/experiments:/experiments \
        container/sclong_v1.0.0.sif \
        python /experiments/additive_pooling_test.py \
          --data-root /groups/tprice/pipelines/references/sclong \
          --output-dir /scratch/juno/$USER/sclong_results/additive_pooling_full \
          --n-cells all --seed 42 \
          --gene-mapping-version v2_hgnc_plus_biomart_synonyms --pooling measured-only \
          --normalization cpm

(--pooling only affects A/B/C -- D always runs in reindex-to-dataset mode regardless, see
module docstring above. Use --pooling full for run 1 since it doesn't matter for D and
keeps A directly comparable to the as-shipped baseline.)

See the decision rule printed at the end of this script's own output for how to read A/B/C/D
together, and ROADMAP.md §16 for the full comparison against the source notebook. Also
inspect the per-celltype breakdown (diagnose_per_celltype.py against this run's *_ce.npy
for each variant) for the 5 historically hardest groups (mast, quiescent_stellate,
endothelial, schwann, macrophage) -- the old n=20 test could not see these groups at all
(expected count in a 20-cell uniform draw out of 16,382: schwann 0.03, mast 0.05,
macrophage 0.10, quiescent_stellate 0.24, endothelial 0.38).
"""
import argparse
import pickle
import sys
import time
from pathlib import Path

import numpy as np
import scanpy as sc
import torch
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "pipeline"))
sys.path.insert(0, "/opt/scLong")  # container PYTHONPATH; harmless no-op if already there

from performer_pytorch_cont.ding_models import DualEncoderSCFM  # noqa: E402
from eval_utils import evaluate, print_sys  # noqa: E402
# get_cell_emb_eq11_reindexed's own forward pass is NOT called here -- variant D below
# inlines the same combined = concat(E, x') + reindex(filler='mean') + sum logic so it
# can reuse this loop's single shared forward pass instead of triggering a second one.
# Cross-checked equivalent to get_cell_emb_eq11_reindexed by
# experiments/sanity_gate_eq11_reindex.py.
from run_zero_shot_batch_integration import (  # noqa: E402
    reindex_tensor_universal, resolve_gene_mapping_path,
    cpm_renormalize, cpm_norescale_renormalize, literal_renormalize, shipped_max10_rescale,
)

p = argparse.ArgumentParser()
p.add_argument("--data-root", type=str, default="/data")
p.add_argument("--output-dir", type=str, default="/data/results/additive_pooling")
p.add_argument("--batch-size", type=int, default=32)
p.add_argument("--n-cells", type=str, default="20")
p.add_argument("--seed", type=int, default=42)
p.add_argument("--gene-mapping-version", type=str, default="v2_hgnc_plus_biomart_synonyms")
p.add_argument("--pooling", choices=["full", "measured-only"], default="full")
p.add_argument("--normalization",
                choices=["as-shipped", "cpm", "literal", "cpm-norescale", "shipped-max10"],
                default="as-shipped",
                help="Mirrors run_zero_shot_batch_integration.py's --normalization exactly "
                     "(same functions, imported not reimplemented). Default 'as-shipped' "
                     "preserves this script's original behavior (adata.X as-is) for "
                     "backward compatibility with the n=20 job-316699 result. Pass "
                     "'cpm' to compare A/B/C under the same normalization that produced "
                     "the project's 0.8550 reference config (job 316352) -- the old "
                     "'CLOSED, NEGATIVE' verdict never tested this combination.")
args = p.parse_args()

root = Path(args.data_root)
gene_meta = root / "gene_meta"
out_dir = Path(args.output_dir)
out_dir.mkdir(parents=True, exist_ok=True)
n_cells = 1e10 if args.n_cells == "all" else int(args.n_cells)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print_sys(f"device={device}")

t0 = time.time()
with open(gene_meta / "gocont_4096_48m_pretrain_1b_mix.pkl", "rb") as f:
    hp = pickle.load(f)
hp["gene2vec_file"] = str(gene_meta / "selected_gene2vec_27k.npy")

model = DualEncoderSCFM(**hp).to(device)
ckpt = torch.load(str(gene_meta.parent / "checkpoints" /
                       "gocont_4096_48m_pretrain_1b_mix_2024-02-05_16-23-37.pth"),
                   map_location="cpu")
model.load_state_dict(ckpt["model_state_dict"])
model.to(device)
for param in model.parameters():
    param.requires_grad = False
model.eval()
print_sys(f"model loaded, elapsed={time.time()-t0:.1f}s")

symbol2ens_path = resolve_gene_mapping_path(gene_meta, args.gene_mapping_version)
with open(symbol2ens_path, "r") as f:
    symbol2ens = {
        line.split(",")[0]: line.split(",")[1].rstrip("\n")
        for line in f.readlines() if line.split(",")[1] != "unknown"
    }

adata = sc.read_h5ad(str(root / "datasets" / "pancreas_scib.h5ad"))
sc.pp.filter_cells(adata, min_genes=10)
sc.pp.filter_genes(adata, min_cells=10)

n_cells = int(np.min((adata.n_obs, n_cells)))
if adata.n_obs > n_cells:
    print_sys(f"subsampling to {n_cells} cells, seed={args.seed}")
    sc.pp.subsample(adata, n_obs=n_cells, copy=False, random_state=args.seed)

if args.normalization == "as-shipped":
    X_to_use = adata.X
elif args.normalization == "shipped-max10":
    row_max_before = (adata.X.toarray() if hasattr(adata.X, "toarray") else np.asarray(adata.X)).max(axis=1)
    X_to_use = shipped_max10_rescale(adata.X)
    row_max_after = X_to_use.max(axis=1)
    n_at_10 = int(np.sum(np.isclose(row_max_after, 10.0, atol=1e-3)))
    print_sys(f"normalization=shipped-max10: per-cell max before mean={row_max_before.mean():.2f} "
               f"-> after mean={row_max_after.mean():.4f} n_at_max10={n_at_10}/{len(row_max_after)}")
else:  # cpm, literal, cpm-norescale
    if "counts" not in adata.layers:
        print_sys(f"MISSING: adata.layers['counts'] required for --normalization {args.normalization}")
        sys.exit(1)
    row_max_before = (adata.X.toarray() if hasattr(adata.X, "toarray") else np.asarray(adata.X)).max(axis=1)
    renorm_fn = {
        "cpm": cpm_renormalize,
        "literal": literal_renormalize,
        "cpm-norescale": cpm_norescale_renormalize,
    }[args.normalization]
    X_to_use = renorm_fn(adata.layers["counts"])
    row_max_after = X_to_use.max(axis=1)
    n_at_10 = int(np.sum(np.isclose(row_max_after, 10.0, atol=1e-3)))
    print_sys(f"normalization={args.normalization}: per-cell max before mean={row_max_before.mean():.2f} "
               f"-> after mean={row_max_after.mean():.4f} n_at_max10={n_at_10}/{len(row_max_after)}")

input_genes = adata.var.index.tolist()
input_genes = [symbol2ens.get(symbol, f"unknown{i}") for i, symbol in enumerate(input_genes)]
input_mapping = {idx: i for i, idx in enumerate(input_genes)}
input_gene_num = len(input_genes)

with open(gene_meta / "selected_genes_27k.txt", "r") as f:
    scfm_genes = [line.rstrip("\n") for line in f.readlines()]
scfm_genes_pad = scfm_genes + ["PAD"]
scfm_seq_len = len(scfm_genes_pad)
scfm_mapping = {idx: i for i, idx in enumerate(scfm_genes_pad)}
scfm_index_positions = [input_mapping.get(idx, input_gene_num) for idx in scfm_genes_pad]

measured_mask = None
if args.pooling == "measured-only":
    measured_mask = torch.tensor(
        [pos != input_gene_num for pos in scfm_index_positions], dtype=torch.bool, device=device
    )
    print_sys(f"pooling=measured-only: {int(measured_mask.sum())}/{len(scfm_genes_pad)} positions kept")

# For variant D (eq11_reindexed, ROADMAP.md §16) -- opposite-direction mapping, reusing
# scfm_mapping already built above. Computed unconditionally (cheap) so D always runs
# alongside A/B/C in the same pass, regardless of --pooling.
input_index_positions = [scfm_mapping.get(idx, scfm_seq_len) for idx in input_genes]
n_covered = sum(1 for pos in input_index_positions if pos != scfm_seq_len)
print_sys(f"variant D (reindex-to-dataset): {n_covered}/{input_gene_num} dataset genes "
           f"have a real model position (rest mean-imputed)")

X = X_to_use
if hasattr(X, "toarray"):
    X = X.toarray()
X = np.asarray(X)

variant_names = ["A_sum_pool", "B_exp_to_out_alone", "C_additive", "D_eq11_reindexed"]
embeddings = {name: [] for name in variant_names}

batch_starts = list(range(0, n_cells, args.batch_size))
print_sys(f"running {len(batch_starts)} batches, batch_size={args.batch_size}, n_cells={n_cells}")
t_embed = time.time()
for i in tqdm(batch_starts, file=sys.stderr):
    with torch.no_grad():
        x_batch = X[i:i + args.batch_size, :]
        x = torch.tensor(x_batch).to(torch.float32).to(device)
        x_scfm = reindex_tensor_universal(x, scfm_index_positions, dim=1, filler="0", device=device)
        out = model(x_scfm, return_encodings=True)
        merged_decodings = out["merged_decodings"]  # (B, 27875, 200)
        exp_out = model.exp_to_out(merged_decodings).squeeze(-1)  # (B, 27875)
        sum_pool = merged_decodings.sum(dim=-1)  # (B, 27875)
        additive = sum_pool + exp_out  # (B, 27875)

        # Variant D (ROADMAP.md §16) reuses merged_decodings/exp_out directly instead of
        # calling get_cell_emb_eq11_reindexed (which would trigger a second, redundant
        # forward pass) -- same combined = concat(E, x') tensor, just reindexed onto the
        # dataset's own gene ordering (filler='mean') before summing, matching the
        # paper's literal Equation (11).
        combined = torch.cat([merged_decodings, exp_out.unsqueeze(-1)], dim=-1)  # (B, 27875, 201)
        combined = reindex_tensor_universal(
            combined, input_index_positions, dim=1, filler="mean", device=device
        )  # (B, N=dataset genes, 201)
        eq11_reindexed = combined.sum(dim=-1)  # (B, N)

        for name, emb in zip(variant_names[:3], [sum_pool, exp_out, additive]):
            if measured_mask is not None:
                emb = emb[:, measured_mask]
            embeddings[name].append(emb.cpu().numpy())
        embeddings["D_eq11_reindexed"].append(eq11_reindexed.cpu().numpy())
print_sys(f"forward passes done, elapsed={time.time()-t_embed:.1f}s")

# config_tag mirrors run_zero_shot_batch_integration.py's convention (map-..._pool-..._
# norm-...) so file names are self-describing and compatible with
# summarize_ablation_grid.py's filename regex -- the old naming (no mapping/norm in the
# filename) made it impossible to tell, from the filename alone, that job 316699's CSVs
# were an as-shipped run rather than the cpm config they're often compared against.
config_tag = f"map-{args.gene_mapping_version}_pool-{args.pooling}_norm-{args.normalization}"

results = {}
for name in variant_names:
    emb_arr = np.concatenate(embeddings[name], axis=0)
    embedding_key = "X_test"
    adata.obsm[embedding_key] = emb_arr
    res = evaluate(
        adata_=adata, batch_key="batch", label_key=["celltype"], embedding_key=embedding_key,
        res_path=str(out_dir / f"additive_pooling__{name}__{config_tag}__n{n_cells}_seed{args.seed}.csv"),
        bio_conservation=True,
    )
    row = res[res["metric"] == "ASW_label/batch"]
    asw = float(row["value"].values[0]) if len(row) else float("nan")
    results[name] = res.set_index("metric")["value"].to_dict()
    print(f"RESULT {name}: {results[name]}", flush=True)

print(f"\n=== SUMMARY (n={n_cells}, seed={args.seed}, config={config_tag}) ===")
for name, metrics in results.items():
    print(f"  {name}: " + " ".join(f"{k}={v:.4f}" for k, v in metrics.items()))
print("\nDecision rule (revised 2026-08-11, ROADMAP.md §16 -- see module docstring): "
      "judge C and D against THIS RUN's own A (internal control; A should reproduce "
      "0.8550 under norm=cpm/map-v2/pool-measured-only, or reproduce the as-shipped "
      "baseline under norm=as-shipped) and check bio-conservation doesn't fall alongside "
      "any ASW gain. D is the priority comparison -- it's the config closest to the "
      "colleague's 0.9212 notebook run (norm=shipped-max10 reproduces it most faithfully; "
      "norm=cpm tests whether this project's own best normalization lever stacks with "
      "it). Then run diagnose_per_celltype.py on each variant's *_ce.npy and inspect "
      "mast/quiescent_stellate/endothelial/schwann/macrophage specifically -- n=20 could "
      "not see these groups at all.")
print("DONE", flush=True)
